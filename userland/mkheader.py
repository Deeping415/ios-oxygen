#!/usr/bin/env python3
"""mkheader.py OUT.h BLUETOOL_BIN ORIGINAL_PLIST

Writes the C header bsd/dev/vince_userland_data.h with
  vince_bluetool_bin         the stand-in for BlueTool built by .github/workflows/userland.yml
  vince_bluetool_plist_orig  the original launchd job file of com.apple.BlueTool (written back over an earlier fix-up)
"""
import sys

out, binp, plp = sys.argv[1:4]
orig = open(plp, "rb").read()
bin_bytes = open(binp, "rb").read()


def arr(name, data):
    s = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 16):
        s.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    s.append("};")
    s.append(f"static const unsigned {name}_len = {len(data)};")
    return "\n".join(s)


open(out, "w").write("/* generated by userland/mkheader.py; do not edit */\n" + arr("vince_bluetool_bin", bin_bytes) + "\n" +
                     arr("vince_bluetool_plist_orig", orig) + "\n")
print("bin", len(bin_bytes), "orig plist", len(orig))
